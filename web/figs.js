      before: ['学习之前：奖励来得出乎意料', '奖励出现时，多巴胺神经元短暂地密集放电。实际得到的比预期的好，预测误差为正。'],
      after: ['学会之后：线索预示着奖励', '反应提前到了线索出现的时候；奖励本身已经在预料之中，到来时几乎没有额外反应，预测误差约为零。'],
